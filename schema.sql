-- Task Manager: Postgres schema with the checks the database can enforce by itself.
-- Columns are snake_case (Postgres convention); the API maps them to the camelCase.
-- names used in the JSON (remind_at <-> remindAt, owner_id <-> ownerId, and so on).

CREATE TABLE users (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname      text        NOT NULL CHECK (length(trim(firstname)) > 0),
    lastname       text        NOT NULL CHECK (length(trim(lastname)) > 0),
    preferred_name text,
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tasks (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         text        NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 120),
    description   text                 CHECK (length(description) <= 5000),
    deadline      timestamptz,
    status        text        NOT NULL DEFAULT 'Not Started'
                              CHECK (status IN ('Not Started', 'In-Progress')),
    category      text                 CHECK (category IN ('Admin', 'Supply', 'Flight', 'Personal')),
    type          text                 CHECK (type IN ('Follow-up', 'Reminder', 'Sign-off', 'Recurring')),
    priority      text        NOT NULL DEFAULT 'Low'
                              CHECK (priority IN ('Low', 'Medium', 'High')),
    remind_at     timestamptz,
    owner_id      integer     NOT NULL REFERENCES users (id),
    pinned        boolean     NOT NULL DEFAULT false,
    snoozed_until timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    completed_at  timestamptz,
    archived_at   timestamptz,

    -- A reminder after the deadline is no use.
    CONSTRAINT remind_not_after_deadline
        CHECK (remind_at IS NULL OR deadline IS NULL OR remind_at <= deadline),
    -- A snooze needs something to snooze: a deadline or a reminder.
    CONSTRAINT snooze_needs_alert_source
        CHECK (snoozed_until IS NULL OR deadline IS NOT NULL OR remind_at IS NOT NULL),
    -- You can only snooze a reminder that has already been due.
    CONSTRAINT snooze_after_reminder
        CHECK (snoozed_until IS NULL OR remind_at IS NULL OR snoozed_until > remind_at),
    -- Finished or archived tasks do not alert, so they cannot be snoozed.
    CONSTRAINT no_snooze_when_done
        CHECK (snoozed_until IS NULL OR (completed_at IS NULL AND archived_at IS NULL)),
    -- Archived tasks are put away (still listed, marked archived), so they cannot be pinned to the top.
    CONSTRAINT no_pin_when_archived
        CHECK (NOT pinned OR archived_at IS NULL),
    -- Archiving and snoozing are actions taken in the app, so they cannot predate the record.
    -- completed_at has no such rule on purpose: work finished last week can be logged today.
    CONSTRAINT archived_on_or_after_created
        CHECK (archived_at IS NULL OR archived_at >= created_at),
    CONSTRAINT snooze_on_or_after_created
        CHECK (snoozed_until IS NULL OR snoozed_until >= created_at)
);

-- The Today view and the overdue check both filter open tasks by deadline.
CREATE INDEX tasks_open_by_deadline
    ON tasks (owner_id, deadline)
    WHERE completed_at IS NULL AND archived_at IS NULL;
