"""Database tables, as Python classes (SQLModel).

Each class with `table=True` is one table; each annotated attribute is one column.
At startup, main.py calls create_all, which builds the tables from these classes.

schema.sql is the reference, but it never runs. So every CHECK rule and the partial
index from schema.sql are declared here as well; without them the running database
would not enforce any of those rules. Keep the two in sync.

Constraint names match the ones Postgres gives schema.sql, so when a save is rejected,
the error names a rule you can find in that file.
"""
from datetime import datetime, timezone

from sqlalchemy import CheckConstraint, Column, DateTime, Identity, Index, Integer, Text, text
from sqlmodel import Field, SQLModel


def _now():
    """The current time in UTC. Used as the default created_at for rows made in Python."""
    return datetime.now(timezone.utc)


def _timestamptz(nullable=True):
    """Column settings for a timestamp WITH time zone (Postgres timestamptz), as in schema.sql.

    Used as `**_timestamptz()` below: `**` unpacks this dict into named arguments for Field.
    """
    return {"sa_type": DateTime(timezone=True), "nullable": nullable}


class User(SQLModel, table=True):
    __tablename__ = "users"
    # Table-level rules: a first and last name can't be blank.
    __table_args__ = (
        CheckConstraint("length(trim(firstname)) > 0", name="users_firstname_check"),
        CheckConstraint("length(trim(lastname)) > 0", name="users_lastname_check"),
    )

    # Identity(): the database numbers new rows itself (GENERATED BY DEFAULT AS IDENTITY).
    # None until the row is saved.
    id: int | None = Field(default=None, sa_column=Column(Integer, Identity(), primary_key=True))
    firstname: str = Field(sa_type=Text)
    lastname: str = Field(sa_type=Text)
    preferred_name: str | None = Field(default=None, sa_type=Text)  # e.g. "Maverick"
    # Two defaults: default_factory fills it for rows made in Python; server_default
    # (now()) fills it for rows inserted with plain SQL.
    created_at: datetime = Field(
        default_factory=_now, sa_column_kwargs={"server_default": text("now()")}, **_timestamptz(False)
    )


class Task(SQLModel, table=True):
    __tablename__ = "tasks"
    # Every rule the database enforces on its own, copied from schema.sql.
    __table_args__ = (
        # Allowed values and lengths for single columns. schema.sql leaves these unnamed;
        # these are the names Postgres would give them.
        CheckConstraint("length(trim(title)) BETWEEN 1 AND 120", name="tasks_title_check"),
        CheckConstraint("length(description) <= 5000", name="tasks_description_check"),
        CheckConstraint("status IN ('Not started', 'In progress')", name="tasks_status_check"),
        CheckConstraint("category IN ('Admin', 'Supply', 'Flight', 'Personal')", name="tasks_category_check"),
        CheckConstraint("type IN ('Follow-up', 'Reminder', 'Sign-off', 'Recurring')", name="tasks_type_check"),
        CheckConstraint("priority IN ('Low', 'Medium', 'High')", name="tasks_priority_check"),
        # Rules across columns, named as in schema.sql.
        # A reminder after the deadline is no use. A reminder with no deadline is fine.
        CheckConstraint(
            "remind_at IS NULL OR deadline IS NULL OR remind_at <= deadline", name="remind_not_after_deadline"
        ),
        # A snooze needs something to snooze: a deadline or a reminder.
        CheckConstraint(
            "snoozed_until IS NULL OR deadline IS NOT NULL OR remind_at IS NOT NULL",
            name="snooze_needs_alert_source",
        ),
        # You can only snooze a reminder that has already been due.
        CheckConstraint(
            "snoozed_until IS NULL OR remind_at IS NULL OR snoozed_until > remind_at", name="snooze_after_reminder"
        ),
        # Completed or archived tasks don't alert, so they can't be snoozed.
        # (The update route clears the snooze for you; see routes.py.)
        CheckConstraint(
            "snoozed_until IS NULL OR (completed_at IS NULL AND archived_at IS NULL)", name="no_snooze_when_done"
        ),
        # Archived tasks can't be pinned to the top. (The update route unpins for you.)
        CheckConstraint("NOT pinned OR archived_at IS NULL", name="no_pin_when_archived"),
        # Archiving and snoozing happen in the app, so they can't predate the task.
        # completed_at has no such rule on purpose: past work can be logged.
        CheckConstraint("archived_at IS NULL OR archived_at >= created_at", name="archived_on_or_after_created"),
        CheckConstraint("snoozed_until IS NULL OR snoozed_until >= created_at", name="snooze_on_or_after_created"),
        # Partial index: only open tasks (not completed, not archived), by owner and
        # deadline. That is what the Today view and the overdue check look up.
        Index(
            "tasks_open_by_deadline",
            "owner_id",
            "deadline",
            postgresql_where=text("completed_at IS NULL AND archived_at IS NULL"),
        ),
    )

    id: int | None = Field(default=None, sa_column=Column(Integer, Identity(), primary_key=True))
    title: str = Field(sa_type=Text)
    description: str | None = Field(default=None, sa_type=Text)
    deadline: datetime | None = Field(default=None, **_timestamptz())
    # Only these two are stored. Completed = completed_at is set; Overdue = deadline has
    # passed and not completed. Both are worked out, never stored.
    status: str = Field(default="Not started", sa_type=Text, sa_column_kwargs={"server_default": "Not started"})
    category: str | None = Field(default=None, sa_type=Text)  # plain text on purpose, no categories table
    type: str | None = Field(default=None, sa_type=Text)
    priority: str = Field(default="Low", sa_type=Text, sa_column_kwargs={"server_default": "Low"})
    remind_at: datetime | None = Field(default=None, **_timestamptz())
    owner_id: int = Field(foreign_key="users.id")  # must point at an existing user
    pinned: bool = Field(default=False, sa_column_kwargs={"server_default": text("false")})
    snoozed_until: datetime | None = Field(default=None, **_timestamptz())  # quiets the alert, never hides the task
    created_at: datetime = Field(
        default_factory=_now, sa_column_kwargs={"server_default": text("now()")}, **_timestamptz(False)
    )
    completed_at: datetime | None = Field(default=None, **_timestamptz())  # set = completed
    archived_at: datetime | None = Field(default=None, **_timestamptz())  # set = archived
